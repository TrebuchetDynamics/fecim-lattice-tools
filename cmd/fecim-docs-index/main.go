// fecim-docs-index validates the explicit public source policy, then emits
// deterministic build output for both profiles and the embedded Go search core.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"fecim-lattice-tools/workbench/modules/docs"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	rootPath := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "verify generated bytes without writes")
	flag.Parse()
	root, err := os.OpenRoot(*rootPath)
	if err != nil {
		return err
	}
	defer root.Close()
	sources := docs.PublicationPolicy()
	for i := range sources {
		f, err := root.Open(sources[i].Path)
		if err != nil {
			return err
		}
		info, err := f.Stat()
		if err != nil {
			f.Close()
			return err
		}
		if !info.Mode().IsRegular() || info.Size() > docs.MaxDocumentBytes {
			f.Close()
			return fmt.Errorf("source limit: %s", sources[i].Path)
		}
		data, readErr := io.ReadAll(io.LimitReader(f, docs.MaxDocumentBytes+1))
		f.Close()
		if readErr != nil {
			return readErr
		}
		if len(data) > docs.MaxDocumentBytes {
			return fmt.Errorf("source grew beyond limit")
		}
		sources[i].Text = string(data)
	}
	corpus, err := docs.Build(sources)
	if err != nil {
		return err
	}
	outputs := map[string][]byte{}
	marshal := func(v any) []byte { b, _ := json.Marshal(v); return append(b, '\n') }
	outputs["workbench/modules/docs/corpus.json"] = marshal(corpus.Sources)
	type entry struct {
		docs.Document
		Content       string `json:"content"`
		ContentSHA256 string `json:"content_sha256"`
	}
	entries := []entry{}
	for _, d := range corpus.Documents {
		name := "web/public/docs-content/" + d.ID + ".json"
		data := marshal(d)
		outputs[name] = data
		meta := d
		meta.Nodes = nil
		entries = append(entries, entry{meta, "/docs-content/" + d.ID + ".json", docs.Hash(data)})
	}
	outputs["web/public/docs-manifest.json"] = marshal(struct {
		Version   string        `json:"version"`
		Digest    string        `json:"digest"`
		Documents int           `json:"document_count"`
		Bytes     int           `json:"decoded_bytes"`
		PageSize  int           `json:"page_size"`
		Sources   []docs.Source `json:"source_index"`
		Entries   []entry       `json:"documents"`
	}{"fecim-docs/1", corpus.Digest, len(entries), corpus.Bytes, docs.PageSize, func() []docs.Source {
		x := append([]docs.Source{}, corpus.Sources...)
		for i := range x {
			x[i].Text = ""
		}
		return x
	}(), entries})
	// Refuse stale/unknown public output rather than accidentally ship old content.
	if items, e := os.ReadDir(filepath.Join(*rootPath, "web/public/docs-content")); e == nil {
		for _, item := range items {
			if _, ok := outputs["web/public/docs-content/"+item.Name()]; !ok {
				return fmt.Errorf("unknown public output: %s", item.Name())
			}
		}
	}
	for name, data := range outputs {
		if *check {
			old, err := root.ReadFile(name)
			if err != nil || !bytes.Equal(old, data) {
				return fmt.Errorf("generated docs drift: %s", name)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Join(*rootPath, filepath.Dir(name)), 0755); err != nil {
			return err
		}
		if err := root.WriteFile(name, data, 0644); err != nil {
			return err
		}
	}
	fmt.Printf("docs: %d documents, %d decoded bytes, corpus sha256 %s\n", len(entries), corpus.Bytes, corpus.Digest)
	return nil
}
