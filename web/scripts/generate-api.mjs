// The native Go registrations are authoritative. No server/listener is started.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const schema = execFileSync('go', ['run', './workbench/moduleapi/cmd/generate'], { cwd: root, maxBuffer: 16 << 20 });
writeFileSync(resolve(root, 'workbench/moduleapi/openapi.json'), schema);
const ast = await openapiTS(JSON.parse(schema.toString()));
const digest = createHash('sha256').update(schema).digest('hex');
const target = resolve(root, 'web/src/api/generated.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// Generated by npm run generate:api; OpenAPI sha256 ${digest}\n` + astToString(ast));
const pkg = JSON.parse(readFileSync(resolve(root, 'web/package.json'), 'utf8'));
console.log(`Generated Go/Huma OpenAPI sha256 ${digest}; openapi-typescript ${pkg.devDependencies['openapi-typescript']}; openapi-fetch ${pkg.dependencies['openapi-fetch']}`);
